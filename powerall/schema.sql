CREATE TABLE IF NOT EXISTS schema_version(version integer PRIMARY KEY);
CREATE TABLE IF NOT EXISTS users(id text PRIMARY KEY, username text UNIQUE NOT NULL,
 password text NOT NULL, credentials bytea, created bigint NOT NULL);
CREATE TABLE IF NOT EXISTS sessions(token text PRIMARY KEY, user_id text NOT NULL REFERENCES users ON DELETE CASCADE,
 csrf text NOT NULL, expires bigint NOT NULL);
CREATE INDEX IF NOT EXISTS sessions_user ON sessions(user_id,expires DESC);
CREATE INDEX IF NOT EXISTS sessions_expiry ON sessions(expires);
CREATE TABLE IF NOT EXISTS invites(token text PRIMARY KEY, expires bigint NOT NULL);
CREATE TABLE IF NOT EXISTS attempts(key text NOT NULL, instant bigint NOT NULL);
CREATE INDEX IF NOT EXISTS attempts_lookup ON attempts(key,instant);
CREATE TABLE IF NOT EXISTS meters(
 tenant_id text NOT NULL DEFAULT current_setting('app.tenant_id') REFERENCES users ON DELETE CASCADE,
 id text NOT NULL, provider text NOT NULL, provider_entity text NOT NULL, resource_id text NOT NULL,
 cost_resource_id text, name text NOT NULL, unit text NOT NULL DEFAULT 'kWh', active integer NOT NULL DEFAULT 1,
 PRIMARY KEY(tenant_id,id), UNIQUE(tenant_id,resource_id));
CREATE TABLE IF NOT EXISTS readings(
 tenant_id text NOT NULL DEFAULT current_setting('app.tenant_id') REFERENCES users ON DELETE CASCADE,
 meter_id text NOT NULL, start bigint NOT NULL, kwh text NOT NULL, updated bigint NOT NULL,
 PRIMARY KEY(tenant_id,meter_id,start));
CREATE INDEX IF NOT EXISTS readings_retention ON readings(start);
CREATE TABLE IF NOT EXISTS tariffs(
 tenant_id text NOT NULL DEFAULT current_setting('app.tenant_id') REFERENCES users ON DELETE CASCADE,
 id text NOT NULL, meter_id text NOT NULL, source text NOT NULL, label text NOT NULL,
 effective_from bigint NOT NULL, effective_to bigint, rate text NOT NULL, standing text NOT NULL,
 windows text NOT NULL, clock text NOT NULL, vat text NOT NULL, warning text,
 PRIMARY KEY(tenant_id,id));
CREATE INDEX IF NOT EXISTS tariff_lookup ON tariffs(tenant_id,meter_id,effective_from);
CREATE TABLE IF NOT EXISTS sync_runs(
 tenant_id text NOT NULL DEFAULT current_setting('app.tenant_id') REFERENCES users ON DELETE CASCADE,
 id bigint GENERATED BY DEFAULT AS IDENTITY, started bigint NOT NULL, finished bigint,
 status text NOT NULL, phase text NOT NULL, imported integer NOT NULL DEFAULT 0,
 error text, warnings text NOT NULL DEFAULT '[]', PRIMARY KEY(tenant_id,id));
CREATE TABLE IF NOT EXISTS settings(
 tenant_id text NOT NULL DEFAULT current_setting('app.tenant_id') REFERENCES users ON DELETE CASCADE,
 key text NOT NULL, value text NOT NULL, PRIMARY KEY(tenant_id,key));
